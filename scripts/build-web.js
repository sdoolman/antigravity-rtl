import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const core = fs.readFileSync(path.join(ROOT, 'bin', 'rtl-core.js'), 'utf8');
const payload = fs.readFileSync(path.join(ROOT, 'bin', 'payload.js'), 'utf8')
    .replace('__RTL_CORE__', () => JSON.stringify(core));

const ideClient = core + '\n' + fs.readFileSync(path.join(ROOT, 'bin', 'ide-client.js'), 'utf8');
const ideMain = fs.readFileSync(path.join(ROOT, 'bin', 'ide-main.js'), 'utf8');
const remoteClient = fs.readFileSync(path.join(ROOT, 'bin', 'remote-client.js'), 'utf8');
const extensionManifest = fs.readFileSync(path.join(ROOT, 'extension', 'manifest.json'), 'utf8');

const output = `// Auto-generated by scripts/build-web.js - DO NOT EDIT MANUALLY
export const RTL_PAYLOAD = ${JSON.stringify(payload)};
export const IDE_CLIENT_CODE = ${JSON.stringify(ideClient)};
export const IDE_MAIN_CODE = ${JSON.stringify(ideMain)};
export const REMOTE_CLIENT_CODE = ${JSON.stringify(remoteClient)};
export const EXTENSION_MANIFEST = ${JSON.stringify(extensionManifest)};

export const ANCHOR = 'void win.loadURL(url);';
export const IDE_HOOK = "import './antigravity-rtl-main.js';";
export const PATCH_START = '/* ANTIGRAVITY RTL PATCH */';
export const PATCH_END = '/* END ANTIGRAVITY RTL PATCH */';
export const PATCH_BLOCK = /\\/\\* ANTIGRAVITY RTL PATCH \\*\\/[\\s\\S]*?\\/\\* END ANTIGRAVITY RTL PATCH \\*\\//;
`;

fs.writeFileSync(path.join(ROOT, 'web', 'payload-bundle.js'), output, 'utf8');
console.log('Successfully built web/payload-bundle.js with App, IDE, and CLI Remote bundles');
